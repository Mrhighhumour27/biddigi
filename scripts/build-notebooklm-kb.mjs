function buildNotebookLmPack() {
  const distDir = path.join(ROOT_DIR, 'docs', 'notebooklm-kb', 'dist');
  fs.mkdirSync(distDir, { recursive: true });

  for (const src of KB_SOURCES) {
    const filePath = path.join(distDir, src.filename);
    fs.writeFileSync(filePath, src.content + '\n', 'utf8');
  }

  // Also include ADR-004 and ADR-005 full contents in a master NotebookLM bundle
  const adr004Path = path.join(ROOT_DIR, 'docs', 'adr', 'ADR-004-cinematic-v3.md');
  const adr005Path = path.join(ROOT_DIR, 'docs', 'adr', 'ADR-005-signal-architecture.md');
  const adr004 = fs.existsSync(adr004Path) ? fs.readFileSync(adr004Path, 'utf8') : '';
  const adr005 = fs.existsSync(adr005Path) ? fs.readFileSync(adr005Path, 'utf8') : '';

  const masterBundle = [
    '# Biddigi Master AdTech Standards & Architecture NotebookLM Pro Pack',
    `Generated: 2025-05-15T18:30:00.000Z`,
    ...KB_SOURCES.map((s) => `\n---\n\n${s.content}`),
    '\n---\n\n' + adr004,
    '\n---\n\n' + adr005,
  ].join('\n');

  fs.writeFileSync(
    path.join(distDir, '00-biddigi-master-notebooklm-pack.md'),
    masterBundle,
    'utf8'
  );

  // Write frontend JSON citation index
  const dataDir = path.join(ROOT_DIR, 'src', 'data');
  fs.mkdirSync(dataDir, { recursive: true });
  const citationIndex = {
    packVersion: '2025.05.v3',
    notebookLmReady: true,
    totalDocuments: KB_SOURCES.length + 1,
    sources: KB_SOURCES.map(({ id, badge, title, filename, sectionRef, keyInvariant }) => ({
      id,
      badge,
      title,
      filename: `docs/notebooklm-kb/dist/${filename}`,
      sectionRef,
      keyInvariant,
    })),
  };

  fs.writeFileSync(
    path.join(dataDir, 'notebooklmCitations.json'),
    JSON.stringify(citationIndex, null, 2),
    'utf8'
  );

  console.log(
    `[build-notebooklm-kb] Compiled ${KB_SOURCES.length} standards documents + master bundle into ${distDir}`
  );
}

buildNotebookLmPack();
